#!/usr/bin/env node
/**
 * Generate or check a project-local verification skill from an approved feature
 * manifest. Never executes project commands or overwrites existing files.
 */
import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, readdir, realpath, writeFile } from 'node:fs/promises';
import { isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const idOk = (x) => typeof x === 'string' && /^[a-z][a-z0-9-]{1,45}$/.test(x);
const words = (x) => typeof x === 'string' && x.length > 2 && x.length < 260
  && !/[\r\n`<>]/.test(x);
const list = (v) => Array.isArray(v) && v.length > 0 && v.every(x =>
  typeof x === 'string' && x.length > 0 && x.length < 400 && !/[\r\n\0]/.test(x));
const within = (parent, candidate) => {
  const r = relative(parent, candidate);
  return r === '' || (r !== '..' && !r.startsWith('..' + sep) && !isAbsolute(r));
};

export function validateProfile(profile) {
  if (profile?.schema !== 1 || !idOk(profile.app?.id) || !words(profile.app?.name)
    || !list(profile.launch?.argv) || !list(profile.doctor?.argv)
    || !Array.isArray(profile.features) || !profile.features.length) throw Error('Invalid verification profile');
  const seen = new Set();
  for (const f of profile.features) {
    if (!idOk(f?.id) || seen.has(f.id) || !words(f.title) || !words(f.entry)
      || !words(f.expected) || !list(f.drive?.argv)
      || !Array.isArray(f.sources) || !f.sources.length || f.sources.some(s => typeof s !== 'string'
        || !s || isAbsolute(s) || s.split(/[\\/]/).includes('..') || /[\r\n*?]/.test(s)))
      throw Error('Invalid or duplicate feature');
    seen.add(f.id);
  }
  return profile;
}

export function renderProfile(profile) {
  validateProfile(profile);
  const marker = '<!-- generated by Codex Toolkit project-verification; source: verification-profile.json -->';
  const description = JSON.stringify('Verify the real ' + profile.app.name + ' user journeys when this project changes behavior.');
  const instructions = [
    marker, '---', 'name: verify-' + profile.app.id,
    'description: ' + description,
    '---', '', '# Verify ' + profile.app.name, '',
    'This project-local skill is a controlled recipe, not proof that a feature works.',
    'Consult project source and relevant toolchain instructions before each use.',
    '',
    '## Launch and doctor', '',
    'Start an isolated instance with this exact argument array (no nested shell string):',
    '```json', JSON.stringify(profile.launch.argv), '```',
    'Only drive an instance started for this verification run; never use personal or production sessions.',
    'Confirm readiness with the existing health check:',
    '```json', JSON.stringify(profile.doctor.argv), '```',
    'If readiness fails, do not drive; report the blocker and tear down only what you started.',
    '',
    '## Feature map', '',
    'Read features/README.md, then the selected feature file. For each feature:',
    '1. Exercise its user-visible entry point with the declared harness and isolated data.',
    '2. Capture the action, observed state, side effect, and relevant logs/screenshots.',
    '3. Compare against expected outcomes and failure/recovery states.',
    '4. Preserve evidence outside ephemeral instances, even after teardown.',
    '5. Never declare an unexecuted recipe as PASS.',
    '',
    '## Maintenance', '',
    'Use project-verification.mjs check after feature changes to detect map drift.',
    'Do not rewrite product code to make the verification map pass.',
    'Do not delete/recreate this skill automatically; reconcile user edits first.', '',
  ].join('\n');
  const features = profile.features.map(f => '- [' + f.title + '](' + f.id + '.md) — ' + f.entry);
  const all = new Map([
    ['SKILL.md', instructions],
    ['features/README.md', [marker, '# User-facing verification map', '',
      ...features, '', 'A listed recipe has not necessarily been executed.', ''].join('\n')],
    ['verification-profile.json', JSON.stringify(profile, null, 2) + '\n'],
  ]);
  for (const f of profile.features) all.set('features/' + f.id + '.md', [
    marker, '# ' + f.title, '',
    '## User entry point', f.entry, '',
    '## Exact drive arguments', '```json', JSON.stringify(f.drive.argv), '```', '',
    '## Expected observable outcome', f.expected, '',
    '## Source files to recheck', f.sources.join(', '), '',
    '## Evidence to keep',
    'Capture the action, observed result, process/exit state, and durable side effect.',
    'Report missing credentials or tools as unverified rather than claiming success.', '',
  ].join('\n'));
  return all;
}

async function noSymlinkAncestors(root, output) {
  let cur = root;
  for (const part of relative(root, output).split(sep).filter(Boolean)) {
    cur = join(cur, part);
    const info = await lstat(cur).catch(error => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (info?.isSymbolicLink()) throw Error('Symlink in output path');
  }
}

async function cli(argv) {
  const command = argv[0];
  if (!['generate', 'check'].includes(command)) throw Error('Use generate or check');
  const opts = {};
  for (let i = 1; i < argv.length; i++) {
    const key = argv[i];
    if (!['--workspace', '--manifest', '--out', '--write'].includes(key) || key in opts)
      throw Error('Unknown or duplicate option: ' + key);
    if (key === '--write') opts[key] = true;
    else if (!argv[i + 1] || argv[i + 1].startsWith('--')) throw Error('Missing value for ' + key);
    else opts[key] = argv[++i];
  }
  if (!opts['--workspace'] || !opts['--manifest'] || !opts['--out']) throw Error('Workspace, manifest, and output required');
  if (command === 'check' && opts['--write']) throw Error('Cannot write during check');
  const workspace = await realpath(resolve(opts['--workspace']));
  const manifest = resolve(workspace, opts['--manifest']);
  if (!within(workspace, manifest)) throw Error('Manifest must be within workspace');
  const resolvedManifest = await realpath(manifest);
  if (!within(workspace, resolvedManifest)) throw Error('Manifest must be within workspace');
  const profile = validateProfile(JSON.parse(await readFile(resolvedManifest, 'utf8')));
  const output = resolve(workspace, opts['--out']);
  if (!within(join(workspace, '.agents', 'skills'), output)
    || output !== join(workspace, '.agents', 'skills', 'verify-' + profile.app.id))
    throw Error('Output must be .agents/skills/verify-<app-id> within workspace');
  await noSymlinkAncestors(workspace, output);
  const files = renderProfile(profile);
  const fingerprints = {};
  for (const f of profile.features) {
    for (const relativeFile of f.sources) {
      const file = resolve(workspace, relativeFile);
      if (!within(workspace, file) || !within(workspace, await realpath(file)))
        throw Error('Source reference escapes workspace');
      const bytes = await readFile(file);
      fingerprints[relativeFile] = createHash('sha256').update(bytes).digest('hex');
    }
  }
  files.set('source-fingerprints.json', JSON.stringify(fingerprints, Object.keys(fingerprints).sort(), 2) + '\n');
  if (command === 'check') {
    const actual = [];
    async function walk(path, prefix = '') {
      for (const entry of await readdir(path, { withFileTypes: true })) {
        if (entry.isSymbolicLink()) throw Error('Unexpected symlink in generated skill');
        const rel = prefix ? prefix + '/' + entry.name : entry.name;
        if (entry.isDirectory()) await walk(join(path, entry.name), rel);
        else if (entry.isFile()) actual.push(rel);
        else throw Error('Unexpected file kind: ' + rel);
      }
    }
    await walk(output);
    if (actual.sort().join('\n') !== [...files.keys()].sort().join('\n'))
      throw Error('Verification feature map has missing or unexpected files');
    for (const [name, expected] of files)
      if (await readFile(join(output, name), 'utf8') !== expected)
        throw Error('Verification skill drift: ' + name);
    console.log('Verification map is current: ' + profile.features.length + ' features');
    return;
  }
  if (!opts['--write']) {
    console.log('Preview: ' + [...files.keys()].join(', ') + ' under ' + output);
    return;
  }
  try { await lstat(output); throw Error('Refusing to overwrite existing verification skill'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  // --write explicitly authorizes only this new, bounded output directory.
  await mkdir(output, { recursive: true });
  await mkdir(join(output, 'features'));
  for (const [name, content] of files)
    await writeFile(join(output, name), content, { encoding: 'utf8', flag: 'wx' });
  console.log('Created verify-' + profile.app.id + ' with ' + profile.features.length + ' features');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  cli(process.argv.slice(2)).catch(error => {
    console.error('Project verification: ' + error.message);
    process.exitCode = 2;
  });
